#!/usr/bin/env python3
"""Generate the deterministic Urban Macro geometry (config/layout.ini).

19 sites on a hexagonal lattice (ISD 500 m), 3 sectors per site (boresights
30/150/270 deg, i.e. pointing at the vertices of the site hexagon), 57 cells.
Site 0 is the central one: its 3 sectors are full-stack gNBs, the other 54
sectors are ExtCells.
"""
import math
import sys
from pathlib import Path

ISD = 500.0
CENTER = (1200.0, 1200.0)            # keeps all coordinates positive
BORESIGHTS = (30.0, 150.0, 270.0)    # deg, counter-clockwise from +x


def sites():
    """Axial hex coordinates within two rings of the origin -> (x, y), centre first."""
    pts = []
    for q in range(-2, 3):
        for r in range(-2, 3):
            if abs(q + r) <= 2:
                x = ISD * (q + r / 2)
                y = ISD * r * math.sqrt(3) / 2
                pts.append((math.hypot(x, y), math.atan2(y, x), x, y))
    pts.sort()
    return [(CENTER[0] + x, CENTER[1] + y) for _, _, x, y in pts]


def main_full(root):
    """layout_full.ini for UrbanMacroFull: 57 gNBs + one saturating load UE per non-central cell."""
    s = sites()
    out = ["# GENERATED by scripts/gen_layout.py --full -- do not edit", ""]
    k = 0
    load_ues = []
    for si, (x, y) in enumerate(s):
        for az in BORESIGHTS:
            out += [f"*.gnb[{k}].mobility.initialX = {x:.1f}m",
                    f"*.gnb[{k}].mobility.initialY = {y:.1f}m",
                    f'*.gnb[{k}].cellularNic.phy.txDirection = "ANISOTROPIC"',
                    f"*.gnb[{k}].cellularNic.phy.txAngle = {az:.0f}deg", ""]
            if si > 0:
                load_ues.append((x + 120 * math.cos(math.radians(az)), y + 120 * math.sin(math.radians(az))))
            k += 1
    for j, (ux, uy) in enumerate(load_ues):
        i = 30 + j
        out += [f"*.ue[{i}].mobility.typename = \"StationaryMobility\"",
                f"*.ue[{i}].mobility.initialX = {ux:.1f}m", f"*.ue[{i}].mobility.initialY = {uy:.1f}m",
                f"*.ue[{i}].cellularNic.nrChannelModel[0].insideBuilding = false",
                f"*.server.app[{i}].packetSize = 1400B", f"*.server.app[{i}].samplingTime = 0.4ms", ""]
    (root / "config" / "layout_full.ini").write_text("\n".join(out) + "\n")
    print("wrote layout_full.ini:", k, "gNBs,", len(load_ues), "load UEs")


def main():
    s = sites()
    assert len(s) == 19 and s[0] == CENTER
    out = ["# GENERATED by scripts/gen_layout.py -- do not edit", ""]
    for k, az in enumerate(BORESIGHTS):
        out += [f"*.gnb[{k}].mobility.initialX = {CENTER[0]:.1f}m",
                f"*.gnb[{k}].mobility.initialY = {CENTER[1]:.1f}m",
                f'*.gnb[{k}].cellularNic.phy.txDirection = "ANISOTROPIC"',
                f"*.gnb[{k}].cellularNic.phy.txAngle = {az:.0f}deg", ""]
    n = 0
    for (x, y) in s[1:]:
        for az in BORESIGHTS:
            out += [f"*.extCell[{n}].positionX = {x:.1f}m",
                    f"*.extCell[{n}].positionY = {y:.1f}m",
                    f"*.extCell[{n}].txAngle = {az:.0f}deg"]
            n += 1
    assert n == 54
    Path(__file__).resolve().parent.parent.joinpath("config", "layout.ini").write_text("\n".join(out) + "\n")
    print("wrote layout.ini:", len(s), "sites,", 3 + n, "cells")


if __name__ == "__main__":
    if "--full" in sys.argv:
        main_full(Path(__file__).resolve().parent.parent)
    else:
        main()
