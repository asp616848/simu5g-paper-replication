#!/usr/bin/env python3
"""Generate per-repetition UE drops (positions/rep<N>.ini).

30 UEs uniformly distributed in the hexagon of the central site (the three
central cell hexagons). The 80% indoor / 20% outdoor split is applied inside the
channel model (indoorFraction = 0.8). Independent RNG stream per repetition so
that results are reproducible.
"""
import math
import sys
from pathlib import Path

import numpy as np

ISD = 500.0
CENTER = (1200.0, 1200.0)
NUM_UE = 30
R = ISD / math.sqrt(3)  # circumradius of the site hexagon (vertices at 30+60k deg)


def in_hexagon(x, y):
    """Hexagon whose edges lie ISD/2 from the centre along the 0, 60, 120 deg axes."""
    return all(abs(x * math.cos(math.radians(a)) + y * math.sin(math.radians(a))) <= ISD / 2
               for a in (0, 60, 120))


def drop_ues(rng, n=NUM_UE):
    pts = []
    while len(pts) < n:
        x, y = rng.uniform(-R, R, 2)
        if in_hexagon(x, y):
            pts.append((CENTER[0] + x, CENTER[1] + y))
    return pts


def write_rep(rep, outdir):
    rng = np.random.default_rng(10_000 + rep)
    pts = drop_ues(rng)
    lines = [f"# GENERATED by gen_positions.py, repetition {rep}"]
    for i, (x, y) in enumerate(pts):
        lines += [f"*.ue[{i}].mobility.initialX = {x:.2f}m",
                  f"*.ue[{i}].mobility.initialY = {y:.2f}m"]
    (outdir / f"rep{rep}.ini").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    reps = int(sys.argv[1]) if len(sys.argv) > 1 else 50
    out = Path(__file__).resolve().parent.parent / "positions"
    out.mkdir(exist_ok=True)
    for r in range(reps):
        write_rep(r, out)
    print(f"wrote {reps} UE drops to {out}")
